//Operadores de Atribuição

//operador Atribuidor de Adição

let a = 10;

a += 5; //E igual a a = a + 5

console.log(a);
console.log("");

//operador Atribuidor de Subtração
let b = 5;

b -= 1; //E igual a b = b - 1

console.log(b);
console.log("");

//operador Atribuidor de Muktiplicação
let c = 7;

c *= 2; //E igual a c = c * 2

console.log(c);
console.log("");

//operador Atribuidor de Divisão
let d = 8;

d /= 4; //E igual a d = d / 4

console.log(d);
console.log("");

//operador Atribuidor de Exponenciação
let e = 100;

e **= 2; //E igual a e = e ** 2

console.log(e);
console.log("");

//operador Atribuidor de Resto
let f = 125;

f %= 5; //E igual a f = f % 5

console.log(f);
console.log("");

//operador Atribuidor de Adição com Strings
